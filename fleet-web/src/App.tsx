import React, { useEffect, useState } from 'react';
import { NavLink, Navigate, Route, Routes, useLocation } from 'react-router-dom';
import { api, FleetMe } from './api';
import { useAuth } from './auth';
import DriverSignup from './DriverSignup';
import {
  BedriftPage,
  DriversPage,
  FinancePage,
  ForgotPasswordPage,
  LoginPage,
  OverviewPage,
  ResetPasswordPage,
  TripsPage,
} from './pages';

const NAV = [
  { to: '/', label: 'Oversikt', end: true },
  { to: '/sjaforer', label: 'Sjåfører' },
  { to: '/turer', label: 'Turer' },
  { to: '/okonomi', label: 'Økonomi' },
  { to: '/bedrift', label: 'Bedrift' },
];

export function Brand({ compact = false }: { compact?: boolean }) {
  return (
    <div className={`brand ${compact ? 'compact' : ''}`} aria-label="KJAPP Fleet">
      <div className="brand-word"><span>KJ</span><span className="brand-a">A</span><span>PP</span></div>
      <div className="brand-sub">FLEET</div>
    </div>
  );
}

function PortalShell() {
  const { logout } = useAuth();
  const [fleet, setFleet] = useState<FleetMe | null>(null);
  const [menuOpen, setMenuOpen] = useState(false);
  const location = useLocation();

  useEffect(() => {
    api.fleetMe().then(setFleet).catch(() => setFleet(null));
  }, []);
  useEffect(() => setMenuOpen(false), [location.pathname]);

  const nav = (
    <nav className="portal-nav" aria-label="Fleet-navigasjon">
      {NAV.map((item) => (
        <NavLink key={item.to} to={item.to} end={item.end}
          className={({ isActive }) => `portal-nav-item ${isActive ? 'active' : ''}`}>
          {item.label}
        </NavLink>
      ))}
    </nav>
  );

  return (
    <div className="portal-shell">
      <aside className="portal-sidebar">
        <Brand />
        <div className="sidebar-rule" />
        {nav}
        <div className="sidebar-account">
          <div className="sidebar-company">{fleet?.name || 'KJAPP Fleet'}</div>
          {fleet?.org_number ? <div className="sidebar-org">Org.nr {fleet.org_number}</div> : null}
          <button className="sidebar-logout" onClick={logout}>Logg ut</button>
        </div>
      </aside>

      <div className="mobile-top">
        <Brand compact />
        <button
          className="mobile-menu-button"
          onClick={() => setMenuOpen((v) => !v)}
          aria-label={menuOpen ? 'Lukk meny' : 'Åpne meny'}
          aria-expanded={menuOpen}
        >
          <span className="menu-glyph" aria-hidden="true"><i /><i /><i /></span>
        </button>
      </div>
      {menuOpen ? (
        <div className="mobile-menu-backdrop" onClick={() => setMenuOpen(false)}>
          <div className="mobile-menu" onClick={(e) => e.stopPropagation()}>
            {nav}
            <div className="mobile-menu-company">
              <strong>{fleet?.name || 'KJAPP Fleet'}</strong>
              {fleet?.org_number ? <span>Org.nr {fleet.org_number}</span> : null}
            </div>
            <button className="mobile-logout" onClick={logout}>Logg ut</button>
          </div>
        </div>
      ) : null}

      <main className="portal-main">
        <Routes>
          <Route path="/" element={<OverviewPage />} />
          <Route path="/sjaforer" element={<DriversPage />} />
          <Route path="/turer" element={<TripsPage />} />
          <Route path="/okonomi" element={<FinancePage />} />
          <Route path="/bedrift" element={<BedriftPage />} />
          <Route path="*" element={<Navigate to="/" replace />} />
        </Routes>
      </main>
    </div>
  );
}

export default function App() {
  const { user } = useAuth();
  const location = useLocation();

  // Compatibility route for links generated by the existing /fleet/driver-invites backend.
  // It is intentionally not part of the Fleet navigation.
  if (location.pathname.startsWith('/driver-signup/')) {
    return <Routes><Route path="/driver-signup/:token" element={<DriverSignup />} /><Route path="*" element={<Navigate to="/login" replace />} /></Routes>;
  }

  if (user === undefined) return <div className="full-loader"><div className="spinner" /></div>;

  if (!user) {
    return (
      <Routes>
        <Route path="/login" element={<LoginPage />} />
        <Route path="/glemt-passord" element={<ForgotPasswordPage />} />
        <Route path="/reset-password/:token" element={<ResetPasswordPage />} />
        <Route path="*" element={<Navigate to="/login" replace />} />
      </Routes>
    );
  }
  return <PortalShell />;
}
